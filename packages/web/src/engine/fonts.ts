/**
 * Bitmap fonts for the Painter: variable-width glyphs as rows of '#'/'.', one blank column between
 * glyphs. Three sizes give the text hierarchy of the town:
 *  - FONT_5x7: office signs (big, unmistakable).
 *  - FONT_4x6: zone labels on rugs (long repo names stay readable).
 *  - FONT_3x5: small print: pod names, gauges, bubbles (the prototype's font).
 * Text is drawn in uppercase; diacritics are stripped (É → E). `fit` truncates with an ellipsis.
 */

export interface BitmapFont {
  name: string;
  height: number;
  glyphs: Record<string, string[]>;
}

