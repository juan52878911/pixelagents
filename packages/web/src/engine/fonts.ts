/** Uppercase without diacritics, so every font can draw "Ñandú" as "NANDU". */
export function plain(s: string): string {
  return s.normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase();
}

function glyph(font: BitmapFont, ch: string): string[] | undefined {
  return font.glyphs[ch] ?? (ch === '…' ? font.glyphs['…'] : undefined);
}

/** Width in px of `s` drawn with `font` (one blank column between glyphs, unknown glyphs skipped). */
export function measure(s: string, font: BitmapFont = FONT_3x5, scale = 1): number {
  let w = 0, n = 0;
  for (const ch of plain(s)) { const g = glyph(font, ch); if (g) { w += g[0]!.length; n++; } }
  return (n ? w + n - 1 : 0) * scale;
}

/** `s` if it fits in `maxW` px, else the longest prefix + "…" that does (or "" when nothing fits). */
export function fit(s: string, maxW: number, font: BitmapFont = FONT_3x5, scale = 1): string {
  if (measure(s, font, scale) <= maxW) return s;
  const chars = [...s];
  for (let n = chars.length - 1; n > 0; n--) {
    const t = chars.slice(0, n).join('').trimEnd() + '…';
    if (measure(t, font, scale) <= maxW) return t;
  }
  return measure('…', font, scale) <= maxW ? '…' : '';
}

/** Calls `put(x, y)` for every lit pixel of `s` at (x, y), top-left. Returns the end x. */
export function drawGlyphs(put: (x: number, y: number) => void, s: string, x: number, y: number, font: BitmapFont, scale = 1): number {
  let cx = x;
  for (const ch of plain(s)) {
    const g = glyph(font, ch);
    if (!g) continue;
    const w = g[0]!.length;
    for (let r = 0; r < g.length; r++) {
      const row = g[r]!;
      for (let c = 0; c < w; c++) {
        if (row[c] !== '#') continue;
        for (let dy = 0; dy < scale; dy++) for (let dx = 0; dx < scale; dx++) put(cx + c * scale + dx, y + r * scale + dy);
      }
    }
    cx += (w + 1) * scale;
  }
  return cx;
}
