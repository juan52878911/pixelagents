// Generates the reference tables of docs/config.md from CONFIG_SCHEMA.
// Usage: npx tsx scripts/gen-config-docs.mjs [--check]     (--check fails if docs/config.md is stale)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CONFIG_SCHEMA, DEFAULT_CONFIG } from '../packages/protocol/src/index.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const file = resolve(root, 'docs/config.md');
const BEGIN = '<!-- config-table:begin (generated by scripts/gen-config-docs.mjs; do not edit) -->';
const END = '<!-- config-table:end -->';

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const typeOf = (s) => {
  if (!s) return '';
  if (s.const !== undefined) return `\`${JSON.stringify(s.const)}\``;
  if (s.enum) return s.enum.map((v) => `\`${JSON.stringify(v)}\``).join(' \\| ');
  if (s.oneOf) return s.oneOf.map(typeOf).join(' \\| ');
  if (s.type === 'array') return `${typeOf(s.items) || 'any'}[]`;
  if (s.type === 'object' && s.additionalProperties && typeof s.additionalProperties === 'object' && !s.properties) return `map<string, ${typeOf(s.additionalProperties) || 'any'}>`;
  return s.type ? `\`${s.type}\`` : '';
};
const range = (s) => [s.minimum !== undefined ? `min ${s.minimum}` : '', s.maximum !== undefined ? `max ${s.maximum}` : ''].filter(Boolean).join(', ');
const get = (obj, path) => path.split('.').reduce((o, k) => (o == null ? undefined : o[k]), obj);

const rows = [];
function walk(schema, path, required) {
  const props = schema.properties ?? {};
  for (const [k, s] of Object.entries(props)) {
    const p = path ? `${path}.${k}` : k;
    const def = get(DEFAULT_CONFIG, p);
    const d = def !== undefined && typeof def !== 'object' ? `\`${JSON.stringify(def)}\`` : s.default !== undefined ? `\`${JSON.stringify(s.default)}\`` : '';
    rows.push({ p, type: typeOf(s), req: required.includes(k), def: d, doc: [s.title, s.description, range(s)].filter(Boolean).join('. ') });
    if (s.type === 'object' && s.properties) walk(s, p, s.required ?? []);
  }
}
walk(CONFIG_SCHEMA, '', CONFIG_SCHEMA.required ?? []);

const out = [BEGIN, '', '### Top level and sections', '', '| Key | Type | Required | Default | Notes |', '|---|---|---|---|---|'];
for (const r of rows) out.push(`| \`${r.p}\` | ${r.type} | ${r.req ? 'yes' : ''} | ${r.def} | ${esc(r.doc)} |`);

out.push('', '### Input types (`inputs[]`)', '');
for (const v of CONFIG_SCHEMA.properties.inputs.items.oneOf) {
  out.push(`**${v.title}** (\`type: ${JSON.stringify(v.properties.type.const)}\`)`, '', '| Field | Type | Required | Notes |', '|---|---|---|---|');
  for (const [k, s] of Object.entries(v.properties)) out.push(`| \`${k}\` | ${typeOf(s)} | ${v.required.includes(k) ? 'yes' : ''} | ${esc([s.title, s.description, range(s)].filter(Boolean).join('. '))} |`);
  out.push('');
}

out.push('### Effect entry (`effects[]`)', '', '| Field | Type | Required | Notes |', '|---|---|---|---|');
const ef = CONFIG_SCHEMA.properties.effects.items;
for (const [k, s] of Object.entries(ef.properties)) out.push(`| \`${k}\` | ${typeOf(s)} | ${ef.required.includes(k) ? 'yes' : ''} | ${k === 'layer' ? 'One of the four layers.' : k === 'params' ? 'Filter parameters; see the filter reference in docs/plugins.md.' : ''} |`);
out.push('', END);
const block = out.join('\n');

const current = readFileSync(file, 'utf8');
const a = current.indexOf(BEGIN), b = current.indexOf(END);
if (a < 0 || b < 0) { console.error(`markers missing in ${file}`); process.exit(1); }
const next = current.slice(0, a) + block + current.slice(b + END.length);
if (process.argv.includes('--check')) {
  if (next !== current) { console.error('docs/config.md is stale: run npx tsx scripts/gen-config-docs.mjs'); process.exit(1); }
} else {
  writeFileSync(file, next);
  console.log(`wrote ${rows.length} rows to docs/config.md`);
}
